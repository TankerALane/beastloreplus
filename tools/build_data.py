#!/usr/bin/env python3
"""Merge raw research (tools/data/raw/*.json) into the shipped Lua data.

Standard library only. Writes:
  Data/Abilities.lua   BLP.Abilities[key] = { name, icon, trainerOnly, ranks = { [n] = {...} } }
  Data/Beasts.lua      BLP.Beasts[npcId] = { name, minLevel, maxLevel, zones, teaches, conf }
  tools/data/REVIEW.md every conflict and unverified entry, for a human to check

Confidence (per beast/ability pair, and per ability rank):
  confirmed   two or more independent sources agree
  unverified  only one source
  conflict    sources disagree (the value from the highest-priority source is shipped)
A beast's overall `conf` is the worst of its pairs.

Never hand-edit the generated Lua: change the raw JSON and re-run.

Usage:  python tools/build_data.py [--check]   (--check: validate only, write nothing)
Exit code 1 when a structural check fails (unknown ability/rank, duplicate IDs, bad JSON).
"""
import json
import os
import re
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW_DIR = os.path.join(ROOT, "tools", "data", "raw")
REVIEW_PATH = os.path.join(ROOT, "tools", "data", "REVIEW.md")
ABILITIES_LUA = os.path.join(ROOT, "Data", "Abilities.lua")
BEASTS_LUA = os.path.join(ROOT, "Data", "Beasts.lua")

# Earlier = more trusted when sources disagree.
SOURCE_PRIORITY = ["wowhead-classic", "petopia-classic", "warcraft.wiki.gg"]
# Sites that are the same data under another name count as one source.
SOURCES_CONFIG = os.path.join(ROOT, "tools", "data", "sources.json")
try:
    with open(SOURCES_CONFIG, encoding="utf-8") as _fh:
        _cfg = json.load(_fh)
except (OSError, ValueError):
    _cfg = {}
SOURCE_ALIASES = dict(_cfg.get("aliases") or {})
BEAST_RANK_COPIES = dict(_cfg.get("beastRankCopies") or {})


def variant_rank(raw_source):
    """Within one site, a Forever page beats a Classic page (0 = preferred)."""
    return 0 if "forever" in (raw_source or "").lower() else 1
CONF_ORDER = {"confirmed": 0, "unverified": 1, "conflict": 2}
# Abilities for which a raw file holds Petopia's complete Forever list ("foreverComplete": true).
FOREVER_COMPLETE = set()
KEY_RE = re.compile(r"^[a-z_]+$")

HEADER = ("-- GENERATED by tools/build_data.py from tools/data/raw/*.json.\n"
          "-- Do not edit by hand: change the raw research and re-run the generator.\n")


def src_id(name):
    name = (name or "unknown").strip().lower()
    return SOURCE_ALIASES.get(name, name)


def priority(source):
    return SOURCE_PRIORITY.index(source) if source in SOURCE_PRIORITY else len(SOURCE_PRIORITY)


def norm_name(name):
    return re.sub(r"[^a-z0-9]", "", (name or "").lower())


def as_int(v):
    if isinstance(v, bool) or v is None:
        return None
    if isinstance(v, (int, float)):
        return int(v)
    if isinstance(v, str) and v.strip().isdigit():
        return int(v.strip())
    return None


def lua_str(s):
    s = str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + s + '"'


class Errors:
    def __init__(self):
        self.errors, self.warnings = [], []

    def err(self, msg):
        self.errors.append(msg)

    def warn(self, msg):
        self.warnings.append(msg)


def load_raw(errs):
    files = []
    if not os.path.isdir(RAW_DIR):
        errs.err("missing directory " + RAW_DIR)
        return files
    for fn in sorted(os.listdir(RAW_DIR)):
        if not fn.endswith(".json") or fn.startswith("_"):
            continue
        path = os.path.join(RAW_DIR, fn)
        try:
            with open(path, encoding="utf-8") as fh:
                data = json.load(fh)
        except (OSError, ValueError) as exc:
            errs.err("%s: cannot parse JSON (%s)" % (fn, exc))
            continue
        key = data.get("ability")
        if not isinstance(key, str) or not KEY_RE.match(key):
            errs.err("%s: bad or missing ability key %r" % (fn, key))
            continue
        data["_file"] = fn
        if data.get("foreverComplete") is True:
            FOREVER_COMPLETE.add(key)
        files.append(data)
    return files


def consensus(values_by_source):
    """values_by_source: {source: value}. Returns (value, conf, detail)."""
    vals = {s: v for s, v in values_by_source.items() if v is not None}
    if not vals:
        return None, "unverified", "no source gave a value"
    distinct = set(json.dumps(v, sort_keys=True) for v in vals.values())
    best = sorted(vals, key=priority)[0]
    if len(distinct) > 1:
        return vals[best], "conflict", "; ".join("%s=%s" % (s, vals[s]) for s in sorted(vals))
    if len(vals) >= 2:
        return vals[best], "confirmed", ""
    return vals[best], "unverified", "only " + best


def spell_consensus(spell_by):
    """Spell ID sets agree when they share an ID (one source may also list the 'teach' spell)."""
    if not spell_by:
        return "unverified", "no source gave a spell ID"
    sources = sorted(spell_by)
    for i, a in enumerate(sources):
        for b in sources[i + 1:]:
            if not set(spell_by[a]) & set(spell_by[b]):
                return "conflict", "; ".join("%s=%s" % (s, spell_by[s]) for s in sources)
    if len(sources) >= 2:
        return "confirmed", ""
    return "unverified", "only " + sources[0]


def merge_abilities(files, errs):
    abilities = {}
    review = []
    for data in files:
        key = data["ability"]
        ab = abilities.setdefault(key, {"name": None, "icon": None, "trainerOnly": False,
                                        "ranks": defaultdict(list), "files": [], "notes": []})
        ab["files"].append(data["_file"])
        ab["name"] = ab["name"] or data.get("name")
        ab["icon"] = ab["icon"] or data.get("icon")
        ab["trainerOnly"] = ab["trainerOnly"] or bool(data.get("trainerOnly"))
        ab["notes"].extend(n for n in data.get("notes") or [] if isinstance(n, str))
        for r in data.get("ranks") or []:
            rank = as_int(r.get("rank"))
            if rank is None or rank < 1 or rank > 20:
                errs.err("%s: bad rank %r" % (data["_file"], r.get("rank")))
                continue
            for obs in r.get("observations") or []:
                ab["ranks"][rank].append(obs)

    out = {}
    spell_owner = {}
    for key in sorted(abilities):
        ab = abilities[key]
        if not ab["name"]:
            errs.err("ability %s has no name" % key)
        ranks_out = {}
        for rank in sorted(ab["ranks"]):
            spell_by, lvl_by, tp_by, urls = {}, {}, {}, []
            for obs in sorted(ab["ranks"][rank], key=lambda o: variant_rank(o.get("source"))):
                s = src_id(obs.get("source"))
                ids = sorted(set(i for i in (as_int(x) for x in obs.get("spellIds") or []) if i))
                if ids:
                    spell_by[s] = sorted(set(spell_by.get(s, [])) | set(ids))
                if as_int(obs.get("petLevel")) is not None:
                    lvl_by.setdefault(s, as_int(obs.get("petLevel")))
                if as_int(obs.get("tp")) is not None:
                    tp_by.setdefault(s, as_int(obs.get("tp")))
                if obs.get("url"):
                    urls.append(obs["url"])
            # Spell IDs: union of everything seen is shipped (extra IDs only widen matching),
            # but disagreement is still reported.
            union_ids = sorted(set(i for ids in spell_by.values() for i in ids))
            sconf, sdetail = spell_consensus(spell_by)
            lvl, lconf, ldetail = consensus(lvl_by)
            tp, tconf, tdetail = consensus(tp_by)
            conf = max((sconf, lconf, tconf), key=lambda c: CONF_ORDER[c])
            if not union_ids:
                errs.warn("%s rank %d has no spell ID" % (key, rank))
            for sid in union_ids:
                if sid in spell_owner and spell_owner[sid] != (key, rank):
                    errs.err("spell %d used by %s and %s rank %d" % (sid, spell_owner[sid], key, rank))
                spell_owner[sid] = (key, rank)
            ranks_out[rank] = {"spellIds": union_ids, "petLevel": lvl, "tp": tp, "conf": conf}
            if conf != "confirmed":
                parts = []
                for label, c, d in (("spell IDs", sconf, sdetail), ("pet level", lconf, ldetail),
                                    ("TP", tconf, tdetail)):
                    if c != "confirmed":
                        parts.append("%s %s (%s)" % (label, c, d))
                review.append((conf, "%s rank %d" % (ab["name"] or key, rank), "; ".join(parts),
                               sorted(set(urls))))
        if ranks_out:
            expected = list(range(1, max(ranks_out) + 1))
            if sorted(ranks_out) != expected:
                errs.warn("%s ranks are not contiguous: %s" % (key, sorted(ranks_out)))
        out[key] = {"name": ab["name"] or key, "icon": ab["icon"], "trainerOnly": ab["trainerOnly"],
                    "ranks": ranks_out, "notes": ab["notes"]}
    return out, review


def merge_beasts(files, abilities, errs):
    # Collect observations: npcId -> ability -> list of obs (with resolved source)
    by_npc = defaultdict(lambda: defaultdict(list))
    name_to_id = defaultdict(set)
    nameless = []
    for data in files:
        key = data["ability"]
        seen_in_file = set()
        for b in data.get("beasts") or []:
            npc = as_int(b.get("npcId"))
            obs_list = [o for o in (b.get("observations") or []) if isinstance(o, dict)]
            if npc is not None:
                if npc in seen_in_file:
                    errs.warn("%s: NPC %d listed twice (merged)" % (data["_file"], npc))
                seen_in_file.add(npc)
                for o in obs_list:
                    o["_file"] = data["_file"]
                    by_npc[npc][key].append(o)
                    if o.get("name"):
                        name_to_id[norm_name(o["name"])].add(npc)
            else:
                for o in obs_list:
                    o["_file"] = data["_file"]
                nameless.append((key, data["_file"], obs_list))

    unresolved = []
    for key, fn, obs_list in nameless:
        names = set(norm_name(o.get("name")) for o in obs_list if o.get("name"))
        ids = set()
        for n in names:
            ids |= name_to_id.get(n, set())
        if len(ids) == 1:
            npc = ids.pop()
            by_npc[npc][key].extend(obs_list)
        else:
            label = ", ".join(sorted(set(o.get("name") or "?" for o in obs_list)))
            why = "no NPC ID found" if not ids else "name matches several NPC IDs %s" % sorted(ids)
            unresolved.append((key, label, why, sorted(set(o.get("url") for o in obs_list if o.get("url")))))

    beasts = {}
    review = []
    for npc in sorted(by_npc):
        names, minl, maxl, zones, elite, rare, urls = {}, {}, {}, [], False, False, set()
        teaches = []
        worst = "confirmed"
        for key in sorted(by_npc[npc]):
            rank_by = defaultdict(set)
            rank_variant = {}
            for o in sorted(by_npc[npc][key], key=lambda o: variant_rank(o.get("source"))):
                s = src_id(o.get("source"))
                v = variant_rank(o.get("source"))
                r = as_int(o.get("rank"))
                # A copied beast->rank list counts as the site it copies.
                rs = BEAST_RANK_COPIES.get(o.get("_file"), {}).get(s, s)
                # Only the best variant of a site counts (a Forever page overrides its Classic page).
                if r is not None and rank_variant.setdefault(rs, v) == v:
                    rank_by[rs].add(r)
                if o.get("name"):
                    names.setdefault(s, o["name"])
                if as_int(o.get("minLevel")) is not None:
                    minl.setdefault(s, as_int(o.get("minLevel")))
                if as_int(o.get("maxLevel")) is not None:
                    maxl.setdefault(s, as_int(o.get("maxLevel")))
                for z in o.get("zones") or []:
                    if isinstance(z, str) and z.strip():
                        z = re.sub(r"\s*\((dungeon|raid|instance)\)\s*$", "", z.strip(), flags=re.I)
                        zones.append((priority(s), z))
                elite = elite or o.get("elite") is True
                rare = rare or o.get("rare") is True
                if o.get("url"):
                    urls.add(o["url"])
            # Forever's own complete list exists for this ability, and does not include this beast.
            missing_on_forever = key in FOREVER_COMPLETE and not any(
                variant_rank(o.get("source")) == 0 and src_id(o.get("source")) == "petopia-classic"
                for o in by_npc[npc][key])
            per_source = {}
            multi = False
            for s, rs in rank_by.items():
                if len(rs) > 1:
                    multi = True
                per_source[s] = max(rs)
            rank, conf, detail = consensus(per_source)
            if multi:
                conf = "conflict"
                detail = "a source lists several ranks: " + "; ".join(
                    "%s=%s" % (s, sorted(rs)) for s, rs in sorted(rank_by.items()))
            if rank is None:
                errs.warn("NPC %d %s: no rank given, skipped" % (npc, key))
                continue
            if missing_on_forever:
                conf = "conflict"
                detail = ("listed by Classic sources but not on Petopia's complete Forever list; "
                          + (detail or "")).rstrip("; ")
            ab = abilities.get(key)
            if ab is None:
                errs.err("NPC %d teaches unknown ability %s" % (npc, key))
                continue
            if rank not in ab["ranks"]:
                errs.err("NPC %d teaches %s rank %d, which has no rank data" % (npc, key, rank))
                continue
            if ab["trainerOnly"]:
                errs.warn("NPC %d listed for trainer-only ability %s (kept)" % (npc, key))
            teaches.append({"ability": key, "rank": rank, "conf": conf})
            if CONF_ORDER[conf] > CONF_ORDER[worst]:
                worst = conf
            if conf != "confirmed":
                review.append((conf, "NPC %d %s: %s rank %d" % (
                    npc, names.get(sorted(names, key=priority)[0]) if names else "?",
                    abilities[key]["name"], rank), detail, sorted(urls)))
        if not teaches:
            continue
        name = names[sorted(names, key=priority)[0]] if names else "NPC %d" % npc
        lo, _, _ = consensus(minl)
        hi, _, _ = consensus(maxl)
        if lo is not None and hi is not None and lo > hi:
            lo, hi = hi, lo
        # Level disagreement is reported but does not change the confidence of what it teaches.
        if len(set(minl.values())) > 1 or len(set(maxl.values())) > 1:
            review.append(("note", "NPC %d %s level range" % (npc, name),
                           "min %s / max %s" % (dict(minl), dict(maxl)), sorted(urls)))
        zone_out, seen = [], set()
        for _, z in sorted(zones, key=lambda t: t[0]):
            if z.lower() not in seen:
                seen.add(z.lower())
                zone_out.append(z)
        beasts[npc] = {"name": name, "minLevel": lo, "maxLevel": hi if hi is not None else lo,
                       "zones": zone_out, "elite": elite, "rare": rare,
                       "teaches": sorted(teaches, key=lambda t: (t["ability"], t["rank"])),
                       "conf": worst}
    return beasts, review, unresolved


def write_abilities(abilities):
    lines = [HEADER, "local _, BLP = ...", "BLP.Abilities = {"]
    for key in sorted(abilities):
        ab = abilities[key]
        icon = ("Interface\\Icons\\" + ab["icon"]) if ab["icon"] else None
        lines.append("  [%s] = {" % lua_str(key))
        lines.append("    name = %s," % lua_str(ab["name"]))
        if icon:
            lines.append("    icon = %s," % lua_str(icon))
        if ab["trainerOnly"]:
            lines.append("    trainerOnly = true,")
        lines.append("    ranks = {")
        for rank in sorted(ab["ranks"]):
            r = ab["ranks"][rank]
            fields = ["spellIds = { %s }" % ", ".join(str(i) for i in r["spellIds"])]
            if r["petLevel"] is not None:
                fields.append("petLevel = %d" % r["petLevel"])
            if r["tp"] is not None:
                fields.append("tp = %d" % r["tp"])
            if r["conf"] != "confirmed":
                fields.append("conf = %s" % lua_str(r["conf"]))
            lines.append("      [%d] = { %s }," % (rank, ", ".join(fields)))
        lines.append("    },")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_beasts(beasts):
    lines = [HEADER, "local _, BLP = ...", "BLP.Beasts = {"]
    for npc in sorted(beasts):
        b = beasts[npc]
        fields = ["name = %s" % lua_str(b["name"])]
        if b["minLevel"] is not None:
            fields.append("minLevel = %d" % b["minLevel"])
        if b["maxLevel"] is not None:
            fields.append("maxLevel = %d" % b["maxLevel"])
        fields.append("zones = { %s }" % ", ".join(lua_str(z) for z in b["zones"]))
        t = []
        for x in b["teaches"]:
            extra = "" if x["conf"] == "confirmed" else ", conf = %s" % lua_str(x["conf"])
            t.append("{ ability = %s, rank = %d%s }" % (lua_str(x["ability"]), x["rank"], extra))
        fields.append("teaches = { %s }" % ", ".join(t))
        if b["elite"]:
            fields.append("elite = true")
        if b["rare"]:
            fields.append("rare = true")
        fields.append("conf = %s" % lua_str(b["conf"]))
        lines.append("  [%d] = { %s }," % (npc, ", ".join(fields)))
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_review(abilities, beasts, ab_review, beast_review, unresolved, errs):
    counts = Counter(b["conf"] for b in beasts.values())
    pair_counts = Counter(t["conf"] for b in beasts.values() for t in b["teaches"])
    out = ["# Data review", "",
           "Generated by `tools/build_data.py`. Every entry below still ships (marked "
           "\"unverified\" in game) except the unresolved names at the end. Fix the raw JSON in "
           "`tools/data/raw/` and re-run the generator; never edit `Data/*.lua` by hand.", "",
           "## Counts", "",
           "| | confirmed | unverified | conflict | total |", "|---|---|---|---|---|",
           "| Beasts (worst of what each teaches) | %d | %d | %d | %d |" % (
               counts["confirmed"], counts["unverified"], counts["conflict"], len(beasts)),
           "| Beast/ability pairs | %d | %d | %d | %d |" % (
               pair_counts["confirmed"], pair_counts["unverified"], pair_counts["conflict"],
               sum(pair_counts.values())),
           "", "Abilities: %d (%d ranks)." % (len(abilities),
                                              sum(len(a["ranks"]) for a in abilities.values())), ""]

    def section(title, items, kinds):
        rows = [i for i in items if i[0] in kinds]
        out.append("## %s (%d)" % (title, len(rows)))
        out.append("")
        if not rows:
            out.append("None.")
        for kind, what, detail, urls in sorted(rows, key=lambda r: r[1]):
            out.append("- **%s** — %s%s" % (what, detail or kind,
                                             "".join(" [src](%s)" % u for u in urls[:4])))
        out.append("")

    section("Ability rank conflicts", ab_review, {"conflict"})
    section("Ability ranks with one source", ab_review, {"unverified"})
    section("Beast conflicts", beast_review, {"conflict"})
    section("Beasts with one source", beast_review, {"unverified"})
    section("Level-range disagreements (informational)", beast_review, {"note"})
    out.append("## Unresolved names (not shipped) (%d)" % len(unresolved))
    out.append("")
    if not unresolved:
        out.append("None.")
    for key, label, why, urls in unresolved:
        out.append("- %s: %s — %s%s" % (key, label, why, "".join(" [src](%s)" % u for u in urls[:3])))
    out.append("")
    notes = [(k, n) for k, a in sorted(abilities.items()) for n in a["notes"]]
    out.append("## Researcher notes (%d)" % len(notes))
    out.append("")
    for k, n in notes:
        out.append("- `%s`: %s" % (k, n))
    out.append("")
    if errs.warnings:
        out.append("## Generator warnings (%d)" % len(errs.warnings))
        out.append("")
        out.extend("- " + w for w in errs.warnings)
        out.append("")
    return "\n".join(out), counts, pair_counts


def main(argv):
    check_only = "--check" in argv
    errs = Errors()
    files = load_raw(errs)
    abilities, ab_review = merge_abilities(files, errs)
    beasts, beast_review, unresolved = merge_beasts(files, abilities, errs)
    review, counts, pairs = write_review(abilities, beasts, ab_review, beast_review, unresolved, errs)

    print("abilities: %d, ranks: %d" % (len(abilities), sum(len(a["ranks"]) for a in abilities.values())))
    print("beasts: %d (confirmed %d, unverified %d, conflict %d)" % (
        len(beasts), counts["confirmed"], counts["unverified"], counts["conflict"]))
    print("pairs: confirmed %d, unverified %d, conflict %d; unresolved names: %d" % (
        pairs["confirmed"], pairs["unverified"], pairs["conflict"], len(unresolved)))
    for w in errs.warnings:
        print("warning:", w)
    for e in errs.errors:
        print("ERROR:", e)
    if errs.errors:
        print("FAILED: %d error(s); nothing written." % len(errs.errors))
        return 1
    if check_only:
        print("check OK (nothing written)")
        return 0
    os.makedirs(os.path.dirname(ABILITIES_LUA), exist_ok=True)
    for path, text in ((ABILITIES_LUA, write_abilities(abilities)), (BEASTS_LUA, write_beasts(beasts)),
                       (REVIEW_PATH, review)):
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
